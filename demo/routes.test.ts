describe('demo handlers cover every route the web calls', () => {
  test('all expected routes are registered', () => {
    // `info` carries the method and path at run time; the public type hides them.
    const registered = new Set(
      handlers.map((handler) => {
        const info = handler.info as unknown as { method: string; path: string }
        return `${info.method} ${info.path}`
      }),
    )
    const missing = expected.filter((route) => !registered.has(route))
    expect({ missing, count: expected.length }).toEqual({ missing: [], count: expected.length })
  })
})
